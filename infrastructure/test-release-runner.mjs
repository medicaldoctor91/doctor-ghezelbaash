import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import * as releaseRunner from './run-v2-release.mjs';
assert.equal(releaseRunner.resolveReleaseDate, undefined, 'Release date must come directly from canonical source, not environment override');
assert.equal(releaseRunner.promoteWinner,undefined,'Winner promotion must be removed');
const runnerSource=await fs.readFile(new URL('./run-v2-release.mjs',import.meta.url),'utf8');
assert.doesNotMatch(runnerSource,/APPROVED_BASELINE_SHA256|benchmark-mobile|candidate-a|candidate-b|candidate-c/,'Release runner must not contain freeze/candidate selection machinery');
const workflow=await fs.readFile(new URL('../.github/workflows/build.yml',import.meta.url),'utf8');
assert.doesNotMatch(workflow,/frozen|candidate|benchmark|release\/winner|setup-python|requirements-benchmark|public-assets\.lock/i,'CI must operate on the single final dist without obsolete freeze/candidate machinery');
assert.match(workflow,/npm run release:v2/,'CI must run the final release contract');
assert.match(workflow,/\bdist\//,'CI must retain the final dist artifact');
const packageJson=JSON.parse(await fs.readFile(new URL('../package.json',import.meta.url),'utf8'));
assert.equal(packageJson.engines?.node,'>=22.19.0 <25','Package engine must support Astro 7 on Node 22.19+ while remaining Node 24 compatible');
assert.doesNotMatch(runnerSource,/Node 24 required|split\('\.'\)\[0\].*24/,'Release runner must not hard-require Node 24');
const nvmrc=(await fs.readFile(new URL('../.nvmrc',import.meta.url),'utf8')).trim();
assert.match(nvmrc,/^22\./,'Reference local Node version must use the tested Node 22 line');
const auditSource=await fs.readFile(new URL('./audit-source.mjs',import.meta.url),'utf8');
assert.doesNotMatch(auditSource,/SOURCE\.edition\s*,\s*['"]2026-10-05['"]|Frozen corpus release date/i,'Source audit must validate consistency, not enforce a frozen date');
