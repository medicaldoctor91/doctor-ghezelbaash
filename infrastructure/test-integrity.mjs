import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { sealRelease } from './seal-release.mjs';

const root=await fs.mkdtemp(path.join(os.tmpdir(),'v2-seal-')), dist=path.join(root,'dist');
await fs.mkdir(path.join(dist,'assets'),{recursive:true}); await fs.mkdir(path.join(dist,'media'),{recursive:true});
await fs.writeFile(path.join(dist,'assets/site.0123456789ab.css'),'body{color:#111}');
await fs.writeFile(path.join(dist,'assets/site.abcdef123456.js'),'console.log("ok")');
await fs.writeFile(path.join(dist,'media/photo.abcdef123456.webp'),Buffer.from([1,2,3,4,5]));
await fs.writeFile(path.join(dist,'index.html'),'<!doctype html><html><head><link rel="stylesheet" href="/assets/site.0123456789ab.css"></head><body><script src="/assets/site.abcdef123456.js"></script></body></html>');
await fs.writeFile(path.join(dist,'doctor.vcf'),'BEGIN:VCARD\r\nVERSION:4.0\r\nFN:Test\r\nEND:VCARD\r\n');
await fs.writeFile(path.join(dist,'_headers'),'/*\n  Cache-Control: public, max-age=0, must-revalidate\n');
const result=await sealRelease({distDir:dist,projectRoot:process.cwd(),releaseDate:'2026-10-05'});
const html=await fs.readFile(path.join(dist,'index.html'),'utf8');
const cssHash=createHash('sha384').update(await fs.readFile(path.join(dist,'assets/site.0123456789ab.css'))).digest('base64');
const jsHash=createHash('sha384').update(await fs.readFile(path.join(dist,'assets/site.abcdef123456.js'))).digest('base64');
assert(html.includes(`integrity="sha384-${cssHash}"`));
assert(html.includes(`integrity="sha384-${jsHash}"`));
const manifest=JSON.parse(await fs.readFile(path.join(dist,'integrity-manifest.json'),'utf8'));
assert(manifest.files['/index.html']?.sha256);
assert.equal(manifest.files['/doctor.vcf'].mediaType,'text/vcard','Sealed MIME comes from canonical resource registry');
assert(manifest.files['/assets/site.0123456789ab.css']?.sha256);
assert(!manifest.files['/integrity-manifest.json'], 'manifest must not self-hash');
const sbom=JSON.parse(await fs.readFile(path.join(dist,'sbom.cdx.json'),'utf8'));
assert.equal(sbom.bomFormat,'CycloneDX');
assert.equal(sbom.metadata?.timestamp,undefined,'SBOM must not inject build-time freshness');
assert.equal(sbom.serialNumber,undefined,'Optional random SBOM serial is omitted for reproducible releases');
const firstSbom=await fs.readFile(path.join(dist,'sbom.cdx.json'),'utf8');
await sealRelease({distDir:dist,projectRoot:process.cwd(),releaseDate:'2026-10-05'});
assert.equal(await fs.readFile(path.join(dist,'sbom.cdx.json'),'utf8'),firstSbom,'Same lockfile produces the same SBOM');
const eligibility=JSON.parse(await fs.readFile(path.join(dist,'content-digest-eligibility.json'),'utf8'));
assert(eligibility.eligible['/media/photo.abcdef123456.webp']?.contentDigest.startsWith('sha-256=:'));
assert(!eligibility.eligible['/index.html'], 'HTML must not receive static Content-Digest eligibility');
const headers=await fs.readFile(path.join(dist,'_headers'),'utf8');
assert(!headers.includes('Content-Digest:'), 'Content-Digest must remain pending until live byte-identity verification');
assert.equal(result.manifestFiles,Object.keys(manifest.files).length);
console.log(JSON.stringify({integrityPolicy:'PASS',manifestFiles:result.manifestFiles,sbom:sbom.specVersion},null,2));
