// Only the eight sealed video URLs invoke this Worker. HTML and reader assets
// keep Pages' native static delivery, routing, headers and unlimited requests.
export function createMediaRangeWorker(media,policy={}){
 const discard=response=>{response.body?.cancel().catch(()=>{});};
 const rangeFor=(value,size)=>{
  const match=/^bytes=(\d*)-(\d*)$/i.exec(value?.trim()??'');
  if(!match||(!match[1]&&!match[2]))return null;
  if(!size)return {unsatisfied:true};
  if(!match[1]){const suffix=Number(match[2]);return suffix>0?{start:Math.max(0,size-suffix),end:size-1}:{unsatisfied:true};}
  const start=Number(match[1]),last=match[2]?Number(match[2]):size-1;
  if(match[2]&&last<start)return null;
  return start>=size?{unsatisfied:true}:{start,end:Math.min(last,size-1)};
 };
 return {async fetch(request,env,ctx){
  const url=new URL(request.url),meta=media[url.pathname];
  if(!meta||!['GET','HEAD'].includes(request.method))return env.ASSETS.fetch(request);
  const etag=`"${meta.sha256}"`,cache=globalThis.caches?.default;
  const cacheUrl=new URL(url.origin+url.pathname);cacheUrl.searchParams.set('sealed-media',meta.sha256);
  const key=new Request(cacheUrl),cached=await cache?.match(key);
  let asset=cached;
  if(!asset){
   // Pages ignores Range. Fetch and cache the exact sealed full encoding once,
   // then return only the requested bytes to the browser on partial requests.
   const assetRequest=new Request(url,{headers:{'Accept-Encoding':'identity'}});
   const upstream=await env.ASSETS.fetch(assetRequest);
   if(upstream.status!==200)return upstream;
   const bytes=await upstream.arrayBuffer();
   const digest=[...new Uint8Array(await crypto.subtle.digest('SHA-256',bytes))].map(byte=>byte.toString(16).padStart(2,'0')).join('');
   if(bytes.byteLength!==meta.bytes||digest!==meta.sha256)return new Response('Media unavailable',{status:502,headers:{'Cache-Control':'no-store'}});
   const headers=new Headers(upstream.headers);
   headers.delete('Content-Encoding');headers.delete('Content-Range');
   headers.set('Content-Type',meta.mediaType);headers.set('Content-Length',String(meta.bytes));
   headers.set('Accept-Ranges','bytes');headers.set('ETag',etag);
   headers.set('Cache-Control','public, max-age=3600, must-revalidate');
   asset=new Response(bytes,{headers});
   if(cache){const storing=cache.put(key,asset.clone());if(ctx?.waitUntil)ctx.waitUntil(storing);else await storing;}
  }
  const headers=new Headers(asset.headers),noneMatch=request.headers.get('If-None-Match');
  // _headers does not apply to responses generated by Pages Functions. Apply
  // this release's policy even when identical video bytes reuse an older cache.
  for(const [name,value] of Object.entries(policy.headers??{}))headers.set(name,value);
  headers.delete('Link');headers.set('Cache-Control','public, max-age=3600, must-revalidate');
  if(url.hostname==='doctor-ghezelbaash.pages.dev'||url.hostname.endsWith('.doctor-ghezelbaash.pages.dev'))headers.set('X-Robots-Tag','noindex');
  const modified=Date.parse(headers.get('Last-Modified')??'');
  const since=Date.parse(request.headers.get('If-Modified-Since')??'');
  if((noneMatch&&noneMatch.split(',').some(tag=>tag.trim()==='*'||tag.trim().replace(/^W\//,'')===etag))||(!noneMatch&&Number.isFinite(modified)&&Number.isFinite(since)&&modified<=since)){
   discard(asset);headers.delete('Content-Length');headers.delete('Content-Range');
   return new Response(null,{status:304,headers});
  }
  if(request.method==='HEAD'){discard(asset);return new Response(null,{headers});}
  const ifRange=request.headers.get('If-Range'),rangeDate=Date.parse(ifRange??'');
  const permitted=!ifRange||ifRange===etag||(Number.isFinite(modified)&&Number.isFinite(rangeDate)&&modified<=rangeDate);
  const range=permitted?rangeFor(request.headers.get('Range'),meta.bytes):null;
  if(!range)return new Response(asset.body,{headers});
  if(range.unsatisfied){discard(asset);headers.set('Content-Range',`bytes */${meta.bytes}`);headers.set('Content-Length','0');return new Response(null,{status:416,headers});}
  const {start,end}=range,bytes=await asset.arrayBuffer();
  headers.set('Content-Range',`bytes ${start}-${end}/${meta.bytes}`);
  headers.set('Content-Length',String(end-start+1));
  return new Response(bytes.slice(start,end+1),{status:206,headers});
 }};
}
